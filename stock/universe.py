from __future__ import annotations

from dataclasses import dataclass
from typing import List


@dataclass(frozen=True)
class Asset:
    symbol: str   # sh600585 / sz000001
    name: str     # 海螺水泥
    short: str    # 海螺
    sector: str   # 申万一级行业

    @property
    def code(self) -> str:
        return self.symbol[2:]

    @property
    def file(self) -> str:
        return f"{self.symbol}.csv"

    @property
    def label(self) -> str:
        return f"{self.name} {self.code}.{self.symbol[:2].upper()}"

    @property
    def is_index(self) -> bool:
        return self.sector == "指数"


