def by_file(name: str) -> Asset | None:
    """按文件名（sh600585.csv）反查标的。"""
    for a in UNIVERSE:
        if a.file == name:
            return a
    return None


def sectors() -> List[str]:
    """申万一级行业名，按 STOCKS 里的出现顺序。"""
    out: List[str] = []
    for a in STOCKS:
        if a.sector not in out:
            out.append(a.sector)
    return out
